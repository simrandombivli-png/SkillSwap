-- SkillSwap database schema for MySQL 8.0.16+
-- Fresh database setup only. This file does not migrate existing tables.
-- Do not run this entire script against your existing Workbench database.
-- Existing Workbench database has already been updated separately.
CREATE DATABASE SKILLSWAP;
USE SKILLSWAP;

CREATE TABLE STUDENT (
    STUDENT_ID INT PRIMARY KEY AUTO_INCREMENT,
    NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL UNIQUE,
    PASSWORD VARCHAR(255) NOT NULL,
    CITY VARCHAR(100),
    CREDIT_BALANCE DECIMAL(5,2) DEFAULT 5.00,
    AVAILABILITY VARCHAR(255),
    DEPARTMENT VARCHAR(150) NOT NULL,
    RATING DECIMAL(3,2) NOT NULL DEFAULT 0.00,
    RATING_COUNT INT NOT NULL DEFAULT 0,
    CONSTRAINT CHK_CREDIT_BALANCE CHECK (CREDIT_BALANCE >= 0),
    CONSTRAINT CHK_STUDENT_RATING CHECK (RATING BETWEEN 0 AND 5),
    CONSTRAINT CHK_RATING_COUNT CHECK (RATING_COUNT >= 0)
);

CREATE TABLE SKILL (
    SKILL_ID INT PRIMARY KEY AUTO_INCREMENT,
    SKILL_NAME VARCHAR(100) NOT NULL UNIQUE,
    CATEGORY VARCHAR(100) NOT NULL
);

CREATE TABLE STUDENT_SKILL (
    STUDENT_ID INT NOT NULL,
    SKILL_ID INT NOT NULL,
    SKILL_TYPE VARCHAR(20) NOT NULL,
    PRIMARY KEY (STUDENT_ID, SKILL_ID, SKILL_TYPE),
    FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT(STUDENT_ID),
    FOREIGN KEY (SKILL_ID) REFERENCES SKILL(SKILL_ID),
    CONSTRAINT CHK_SKILL_TYPE CHECK (SKILL_TYPE IN ('OFFERED', 'REQUESTED'))
);

CREATE TABLE BOOKING (
    BOOKING_ID INT PRIMARY KEY AUTO_INCREMENT,
    LEARNER_ID INT NOT NULL,
    TUTOR_ID INT NOT NULL,
    SKILL_ID INT NOT NULL,
    SESSION_DATE DATE NOT NULL,
    START_TIME TIME NOT NULL,
    DURATION DECIMAL(4,2) NOT NULL,
    STATUS VARCHAR(20) DEFAULT 'PENDING',
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (LEARNER_ID) REFERENCES STUDENT(STUDENT_ID),
    FOREIGN KEY (TUTOR_ID) REFERENCES STUDENT(STUDENT_ID),
    FOREIGN KEY (SKILL_ID) REFERENCES SKILL(SKILL_ID),
    CONSTRAINT CHK_BOOKING_STATUS CHECK (STATUS IN ('PENDING', 'CONFIRMED', 'COMPLETED', 'CANCELLED', 'DISPUTED')),
    CONSTRAINT CHK_DIFFERENT_USERS CHECK (LEARNER_ID <> TUTOR_ID),
    CONSTRAINT CHK_DURATION CHECK (DURATION > 0)
);

CREATE TABLE CREDIT_TRANSACTION (
    TRANSACTION_ID INT PRIMARY KEY AUTO_INCREMENT,
    BOOKING_ID INT NOT NULL,
    STUDENT_ID INT NOT NULL,
    TRANSACTION_TYPE VARCHAR(30) NOT NULL,
    AMOUNT DECIMAL(5,2) NOT NULL,
    TRANSACTION_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (BOOKING_ID) REFERENCES BOOKING(BOOKING_ID),
    FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT(STUDENT_ID),
    CONSTRAINT CHK_TRANSACTION_TYPE CHECK (TRANSACTION_TYPE IN ('ESCROW_LOCK', 'ESCROW_RELEASE', 'REFUND'))
);

CREATE TABLE REVIEW (
    REVIEW_ID INT PRIMARY KEY AUTO_INCREMENT,
    BOOKING_ID INT NOT NULL,
    CONSTRAINT UQ_BOOKING_REVIEW UNIQUE (BOOKING_ID),
    REVIEWER_ID INT NOT NULL,
    TUTOR_ID INT NOT NULL,
    RATING DECIMAL(2,1) NOT NULL,
    COMMENT VARCHAR(500),
    REVIEW_DATE DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (BOOKING_ID) REFERENCES BOOKING(BOOKING_ID),
    FOREIGN KEY (REVIEWER_ID) REFERENCES STUDENT(STUDENT_ID),
    FOREIGN KEY (TUTOR_ID) REFERENCES STUDENT(STUDENT_ID),
    CONSTRAINT CHK_REVIEW_RATING CHECK (RATING BETWEEN 1 AND 5)
);

CREATE TABLE DISPUTE (
    DISPUTE_ID INT PRIMARY KEY AUTO_INCREMENT,
    BOOKING_ID INT NOT NULL,
    STUDENT_ID INT NOT NULL,
    REASON VARCHAR(500) NOT NULL,
    STATUS VARCHAR(20) DEFAULT 'OPEN',
    CREATED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (BOOKING_ID) REFERENCES BOOKING(BOOKING_ID),
    FOREIGN KEY (STUDENT_ID) REFERENCES STUDENT(STUDENT_ID),
    CONSTRAINT CHK_DISPUTE_STATUS CHECK (STATUS IN ('OPEN', 'RESOLVED', 'REJECTED'))
);

CREATE VIEW OFFERED_SKILLS AS
SELECT STUDENT.STUDENT_ID, STUDENT.NAME, SKILL.SKILL_NAME, SKILL.CATEGORY
FROM STUDENT
JOIN STUDENT_SKILL ON STUDENT.STUDENT_ID = STUDENT_SKILL.STUDENT_ID
JOIN SKILL ON STUDENT_SKILL.SKILL_ID = SKILL.SKILL_ID
WHERE STUDENT_SKILL.SKILL_TYPE = 'OFFERED';


-- DBMS demonstration queries
-- Demonstration queries below run after the table and view definitions above.


-- 1. JOIN: students and their skills
SELECT STUDENT.NAME, SKILL.SKILL_NAME, STUDENT_SKILL.SKILL_TYPE
FROM STUDENT
JOIN STUDENT_SKILL ON STUDENT.STUDENT_ID = STUDENT_SKILL.STUDENT_ID
JOIN SKILL ON STUDENT_SKILL.SKILL_ID = SKILL.SKILL_ID;

-- 2. JOIN: booking with learner and tutor names
SELECT BOOKING.BOOKING_ID, LEARNER.NAME AS LEARNER_NAME,
       TUTOR.NAME AS TUTOR_NAME, SKILL.SKILL_NAME,
       BOOKING.SESSION_DATE, BOOKING.STATUS
FROM BOOKING
JOIN STUDENT AS LEARNER ON BOOKING.LEARNER_ID = LEARNER.STUDENT_ID
JOIN STUDENT AS TUTOR ON BOOKING.TUTOR_ID = TUTOR.STUDENT_ID
JOIN SKILL ON BOOKING.SKILL_ID = SKILL.SKILL_ID;

-- 3. JOIN: credit transactions with students
SELECT CREDIT_TRANSACTION.TRANSACTION_ID, STUDENT.NAME,
       CREDIT_TRANSACTION.TRANSACTION_TYPE, CREDIT_TRANSACTION.AMOUNT,
       CREDIT_TRANSACTION.BOOKING_ID
FROM CREDIT_TRANSACTION
JOIN STUDENT ON CREDIT_TRANSACTION.STUDENT_ID = STUDENT.STUDENT_ID;

-- 4. GROUP BY: count skills for each student
SELECT STUDENT.NAME, COUNT(STUDENT_SKILL.SKILL_ID) AS TOTAL_SKILLS
FROM STUDENT
JOIN STUDENT_SKILL ON STUDENT.STUDENT_ID = STUDENT_SKILL.STUDENT_ID
GROUP BY STUDENT.STUDENT_ID, STUDENT.NAME;

-- 5. NESTED QUERY: students offering Python
SELECT STUDENT.NAME
FROM STUDENT
WHERE STUDENT.STUDENT_ID IN (
    SELECT STUDENT_SKILL.STUDENT_ID
    FROM STUDENT_SKILL
    WHERE STUDENT_SKILL.SKILL_ID IN (
        SELECT SKILL.SKILL_ID
        FROM SKILL
        WHERE SKILL.SKILL_NAME = 'PYTHON'
    )
    AND STUDENT_SKILL.SKILL_TYPE = 'OFFERED'
);

-- 6. HAVING: students with more than one skill
SELECT STUDENT.NAME, COUNT(STUDENT_SKILL.SKILL_ID) AS TOTAL_SKILLS
FROM STUDENT
JOIN STUDENT_SKILL ON STUDENT.STUDENT_ID = STUDENT_SKILL.STUDENT_ID
GROUP BY STUDENT.STUDENT_ID, STUDENT.NAME
HAVING COUNT(STUDENT_SKILL.SKILL_ID) > 1;

-- 7. ORDER BY: students ranked by credit balance
SELECT STUDENT.STUDENT_ID, STUDENT.NAME, STUDENT.CREDIT_BALANCE
FROM STUDENT
ORDER BY STUDENT.CREDIT_BALANCE DESC;

-- 8. JOIN: reviews with reviewer and tutor names
SELECT REVIEW.REVIEW_ID, REVIEWER.NAME AS REVIEWER_NAME,
       TUTOR.NAME AS TUTOR_NAME, REVIEW.RATING, REVIEW.COMMENT
FROM REVIEW
JOIN STUDENT AS REVIEWER ON REVIEW.REVIEWER_ID = REVIEWER.STUDENT_ID
JOIN STUDENT AS TUTOR ON REVIEW.TUTOR_ID = TUTOR.STUDENT_ID;

-- 9. JOIN: disputes with student names
SELECT DISPUTE.DISPUTE_ID, STUDENT.NAME, DISPUTE.BOOKING_ID,
       DISPUTE.REASON, DISPUTE.STATUS
FROM DISPUTE
JOIN STUDENT ON DISPUTE.STUDENT_ID = STUDENT.STUDENT_ID;

-- 10. VIEW: offered skills (view is created in skillswap.sql)
SELECT * FROM OFFERED_SKILLS;
